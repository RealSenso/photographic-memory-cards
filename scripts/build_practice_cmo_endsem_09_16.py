"""Turns the Endsem Prep problem sets (CMO topics 09-16, problems + full solutions) into practice cards.
Reads ~/Documents/IISc AI/Endsem Prep/CMO/<topic>/_source/ProblemSet_NN.tex, writes practice_cmo_endsem_09_16.js."""
import glob, json, os, re

SRC = "/Users/senso/Documents/IISc AI/Endsem Prep/CMO"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "practice_cmo_endsem_09_16.js")

def grab(s, i):
    """s[i] == '{' -> (content, index after the matching '}')"""
    assert s[i] == "{", s[i:i + 30]
    d = 0
    for j in range(i, len(s)):
        if s[j] == "{": d += 1
        elif s[j] == "}":
            d -= 1
            if d == 0: return s[i + 1:j], j + 1
    raise ValueError("unbalanced")

def boxes(tex):
    out = []
    for m in re.finditer(r"\\(problembox|solutionbox)\{", tex):
        title, j = grab(tex, m.end() - 1)
        body, _ = grab(tex, j)
        out.append((m.group(1), title, body))
    return out

def cmd(s, name, tag):
    """\\name{...} -> <tag>...</tag> with brace matching"""
    key = "\\" + name + "{"
    while key in s:
        i = s.index(key)
        inner, j = grab(s, i + len(key) - 1)
        s = s[:i] + f"<{tag}>" + inner + f"</{tag}>" + s[j:]
    return s

def text(seg):
    seg = re.sub(r"\\(vspace|hspace)\*?\{[^}]*\}", "", seg)
    seg = re.sub(r"\\(medskip|smallskip|bigskip|noindent|par\b|small|large|Large|bfseries|hfill)\s?", " ", seg)
    seg = cmd(seg, "textbf", "b"); seg = cmd(seg, "textit", "i"); seg = cmd(seg, "emph", "i")
    seg = cmd(seg, "textnormal", "span"); seg = cmd(seg, "textsc", "span")
    seg = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", seg)
    seg = seg.replace("\\checkmark", "✓").replace("\\&", "&amp;").replace("\\%", "%").replace("\\_", "_")
    seg = seg.replace("---", "—").replace("--", "–").replace("~", " ")
    seg = re.sub(r"\\begin\{(enumerate|itemize)\}", lambda m: "<ol>" if m.group(1) == "enumerate" else "<ul>", seg)
    seg = re.sub(r"\\end\{(enumerate|itemize)\}", lambda m: "</ol>" if m.group(1) == "enumerate" else "</ul>", seg)
    seg = re.sub(r"\\item\s*", "<li>", seg)
    seg = re.sub(r"(?m)^\s*- ", "<br>• ", seg)
    seg = re.sub(r"\\\\\s*", "<br>", seg)
    seg = re.sub(r"\n\s*\n", "<br><br>", seg)
    seg = seg.replace("\n", " ")
    seg = re.sub(r"(<br>\s*){3,}", "<br><br>", seg)
    return seg

def html(body):
    body = re.sub(r"(?s)\\begin\{align\*?\}(.*?)\\end\{align\*?\}", lambda m: "\\[\\begin{aligned}" + m.group(1) + "\\end{aligned}\\]", body)
    store = []
    def keep(m):
        if m.group(1) is not None: v = "$$" + m.group(1).strip() + "$$"
        elif m.group(2) is not None: v = "$$" + m.group(2).strip() + "$$"
        else: v = "$" + m.group(3) + "$"
        store.append(v.replace("<", "\\lt "))
        return f"@@M{len(store) - 1}@@"
    body = re.sub(r"(?s)\\\[(.*?)\\\]|\$\$(.*?)\$\$|\$(.+?)\$", keep, body)
    h = text(body)
    h = re.sub(r"@@M(\d+)@@", lambda m: store[int(m.group(1))], h)
    h = re.sub(r"^(<br>|\s)+|(<br>|\s)+$", "", h)
    return "<p>" + h.replace("<br><br>", "</p><p>") + "</p>"

def source(title):
    m = re.search(r"\\textbf\{([^{}]*)\}\}\s*$", title.strip())
    return (m.group(1) if m else "").replace("\\&", "&")

cards = []
for t in range(9, 17):
    d = glob.glob(f"{SRC}/{t:02d}_*")[0]
    tex = open(glob.glob(f"{d}/_source/ProblemSet_*.tex")[0]).read()
    bs = boxes(tex)
    k = 0
    for i in range(0, len(bs) - 1, 2):
        (kp, title, q), (ks, _, s) = bs[i], bs[i + 1]
        assert kp == "problembox" and ks == "solutionbox"
        k += 1
        cards.append({"id": 600000 + t * 100 + 20 + k, "subject": "CMO", "topicId": os.path.basename(d),
                      "kind2": "pyq", "source": "Endsem prep · " + source(title), "marks": "",
                      "question": html(q), "solution": html(re.sub(r"^\s*\\textbf\{Step-by-Step[^}]*\}", "", s)),
                      "takeaway": ""})
js = ("/* CMO topics 09-16: the Endsem Prep problem sets (problems and full solutions), one flippable card each.\n"
      "   Generated by scripts/build_practice_cmo_endsem_09_16.py - do not edit by hand. */\n"
      "window.PRACTICE_DATA = (window.PRACTICE_DATA || []).concat(" + json.dumps(cards, indent=1, ensure_ascii=False) + ");\n")
open(OUT, "w").write(js)
print(len(cards), "cards")
