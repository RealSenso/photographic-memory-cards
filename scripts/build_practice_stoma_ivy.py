"""Builds practice_stoma_ivy.js from the Ivy League practice packs (one PDF per StoMA topic).

Run:  python3 scripts/ivy_extract.py "<Topic Packs folder>" <tmp>   (labels + image positions -> <tmp>/index.json)
      python3 scripts/ivy_export.py "<Topic Packs folder>" <tmp>/index.json assets/ivy_stoma   (question images)
      python3 scripts/build_practice_stoma_ivy.py <tmp>/index2.json
Each question is a picture cropped from the original problem set; the packs carry no solutions, so the back of the
card links to the source. Questions that need cards outside the selected 65 keep the pack's note as a STRETCH chip.
"""
import json, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(sys.argv[1]))
t = open(os.path.join(here, '..', 'cards_stoma.js')).read()
cards = json.loads(t[t.index('\n[') + 1:t.rindex(']') + 1])
t1 = open(os.path.join(here, '..', 'cards_data.js')).read()
cards += [c for c in json.loads(t1[t1.index('['):t1.rindex(']') + 1]) if c['subject'] == 'StoMA']
titles = {c['topicId']: c['topicTitle'] for c in cards}

# course -> (full name, url) from the pack headers
src = {}
for v in d.values():
    lines = v['header'].replace('strategic_practi\nce', 'strategic_practice').split('\n')
    for i, l in enumerate(lines):
        if l.startswith('- ') and i + 1 < len(lines) and lines[i + 1].startswith('http'):
            name = l[2:].strip(); src[' '.join(name.split()[:3])] = (name, lines[i + 1].split()[0])
def course(label):
    for k, v in src.items():
        if label.startswith(k): return v
    return (label, '')

# Level filter (12 Nov 2026): keep only questions at IISc StoMA PYQ level or above. The bar is a Test I/II or
# endsem question: 8-10 marks, several parts, a few steps of real work each. Dropped below by id (330000 + topic*100 + n),
# with their images deleted from assets/ivy_stoma/. Ids are not renumbered, so the image names stay put.
DROP = {
    # 01: counting drills, story proofs of binomial identities, one-line set/axiom plug-ins
    330101, 330103, 330105, 330106, 330107, 330108, 330109, 330110, 330111, 330112, 330114, 330120, 330121, 330122, 330123,
    # 02: one-line yes/no facts, single plug-in Bayes, trivial conditional-probability cases, a discussion question
    330201, 330202, 330206, 330210, 330217, 330219, 330226, 330228, 330229, 330230,
    # 03: definitions and one-step facts (same-distribution examples, Geometric CDF, table look-ups, random sign)
    330301, 330302, 330303, 330304, 330305, 330306, 330311,
    # 04: one-line transformations (n - X, X^2 and sqrt X of a uniform, 1 - Beta, inverse transform for Expo)
    330405, 330406, 330408, 330410,
    # 05: MGF and moment drills, one-line indicator or Geometric expectations, a yes/no construction
    330501, 330508, 330509, 330520, 330532, 330533, 330534, 330535,
    # 06: a single Chebyshev plug-in
    330601,
    # 12, 13: one-line identities (two forms of Var(Y|X), MVN subvector and concatenation)
    331201, 331301, 331302,
    # 15, 17: one-line SLLN application, an essay question, and a crop that keeps only the first line (Cornell final Q5)
    331501, 331701, 331703,
    # 19: one-line proofs, plug-in matrix products and calculator exploration
    331901, 331912, 331913, 331914,
    # 20: one-line proof, and questions that need a textbook example or Norvig's data set that the card does not carry
    332007, 332010, 332012, 332013, 332014, 332015,
    # 24: an explain-the-difference question
    332406,
}

esc = lambda s: s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
out = []
for topic, v in sorted(d.items()):
    tnum = int(topic[:2])
    for n, q in enumerate(v['qs'], 1):
        if 330000 + tnum * 100 + n in DROP: continue
        name, url = course(q['label'])
        imgs = ''.join(f'<img class="qimg" src="assets/ivy_stoma/{f}" width="{w}" height="{h}" alt="{esc(q["label"])}" loading="lazy">' for f, w, h in q['files'])
        link = f'<a href="{url}" target="_blank" rel="noopener">{esc(name)}</a>' if url else esc(name)
        beyond = q['tag'].startswith('beyond selection')
        item = {
            'id': 330000 + tnum * 100 + n, 'subject': 'StoMA', 'topicId': topic, 'topicTitle': titles.get(topic, topic),
            'title': q['label'], 'kind2': 'ivy', 'source': q['label'], 'marks': '',
            'question': imgs,
            'solution': f'<p>The Ivy League practice pack gives no solutions for this question.</p><p>Source: {link}, {esc(q["label"])}.</p>'
                        + (f'<p><b>Needs:</b> {esc(q["tag"][len("beyond selection: "):])}</p>' if beyond else '<p>It uses only tools from your 65 selected StoMA cards.</p>'),
        }
        if beyond: item['stretch'] = q['tag'][len('beyond selection: '):]
        out.append(item)
open(os.path.join(here, '..', 'practice_stoma_ivy.js'), 'w').write(
    '/* StoMA Ivy League practice questions (Harvard, Princeton, Columbia, Cornell, Yale problem sets and exams).\n'
    '   Generated by scripts/build_practice_stoma_ivy.py; the question is a picture of the original, the packs have no solutions. */\n'
    'window.PRACTICE_DATA = window.PRACTICE_DATA || [];\nwindow.PRACTICE_DATA.push(' + json.dumps(out, ensure_ascii=False, indent=1) + ');\n')
print(len(out), 'questions kept,', len(DROP), 'dropped;', sum('stretch' in q for q in out), 'stretch;', sorted(src))
