"""Applies the subj_<subject>_*.py patch modules (idempotent) to a subject's cards.

Each module defines SUBJECT ("LAA", ...), FIX = {card_id: {field: value}} and STORY = {card_id: {s, b, f, n}}.
Topic 01 of every subject lives in cards_data.js, the rest in cards_<subject>.js; both are patched.
The STORY dicts are written to story_<subject>.js.
Usage: python3 scripts/apply_subj_refine.py laa
"""
import glob, importlib, json, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
root = os.path.join(here, "..")
key = sys.argv[1].lower()

def load(path):
    text = open(path).read()
    i, j = re.search(r"\[\s*\{", text).start(), text.rindex("]") + 1
    return text[:i], json.loads(text[i:j]), text[j:]

files = {p: load(os.path.join(root, p)) for p in ("cards_data.js", f"cards_{key}.js")}
by_id = {c["id"]: c for _, cards, _ in files.values() for c in cards}

def _light(svg):
    svg = svg.replace('font-weight="bold"', 'font-weight="normal"')
    return re.sub(r'stroke-width="([\d.]+)"', lambda m: f'stroke-width="{min(float(m.group(1)), 1.2):g}"', svg)

story, n_fix, subject, posts = {}, 0, None, []
for p in sorted(glob.glob(os.path.join(here, f"subj_{key}_*.py"))):
    mod = importlib.import_module(os.path.basename(p)[:-3])
    subject = mod.SUBJECT
    for cid, fields in mod.FIX.items():
        assert cid in by_id and by_id[cid]["subject"] == subject, f"unknown card {cid}"
        by_id[cid].update(fields)
        n_fix += 1
    story.update({str(k): v for k, v in getattr(mod, "STORY", {}).items()})
    if hasattr(mod, "POST"): posts.append(mod.POST)

# a bare "<" inside $...$ (e.g. j<k) is read by the browser as the start of a tag and cuts the formula
_TAG = re.compile(r"<(?=/?(span|b|strong|em|i|br|sup|sub)\b)")
def _lt(s):
    fix = lambda m: re.sub(r"<(?!/?(span|b|strong|em|i|br|sup|sub)\b)", r"\\lt ", m.group(0))
    return re.sub(r"\$\$[\s\S]*?\$\$|\$[^$]+\$", fix, s)

for c in by_id.values():
    if c["subject"] != subject: continue
    for post in posts: post(c)   # last passes (e.g. notation) over the finished card
    if c.get("drawingSvg"):
        c["drawingSvg"] = _light(c["drawingSvg"])
    for k in ("math", "statement", "personalConnection", "examTrap", "hint"):
        if isinstance(c.get(k), str): c[k] = _lt(c[k])
    for k in ("breakdown", "coreTranslation"):
        if isinstance(c.get(k), list): c[k] = [_lt(x) for x in c[k]]

for p, (head, cards, tail) in files.items():
    open(os.path.join(root, p), "w").write(head + json.dumps(cards, indent=2) + tail)
open(os.path.join(root, f"story_{key}.js"), "w").write(
    f"/* {subject} story bands: where each card sits in the big picture and what it links to. Generated by scripts/apply_subj_refine.py. */\n"
    "window.STORY_DATA = Object.assign(window.STORY_DATA || {}, " + json.dumps(story, indent=1, ensure_ascii=False) + ");\n")
print(f"{subject}: patched {n_fix} cards, {len(story)} story bands")
